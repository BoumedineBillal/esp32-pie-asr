# names that are the same action (a target's or a place's other forms, as the recognizer may write them): a score
# compares actions with each group's members written as its first
SAME = {
    "kitchen": [("@back right", "@backright"), ("@back left", "@backleft"), ("@front right", "@frontright"),
                ("@front left", "@frontleft"), ("burners@all", "burner@all"),
                ("timer_set:minute timer", "timer_set:timer", "timer_set:a timer")],
}


def same(demo, actions):
    """actions (voice::describe's form) with SAME's groups written as their first"""
    for group in SAME.get(demo, []):
        for other in group[1:]:
            actions = actions.replace(other, group[0])
    return actions

